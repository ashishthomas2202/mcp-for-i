type Table = { toChar: string[]; fromChar: Map<string, number> };

const tables = new Map<number, Table>();

function buildTable(ccsid: number): Table {
  if (ccsid !== 37) throw new Error(`CCSID ${ccsid} is not supported for TN5250 (supported: ${SUPPORTED_CCSIDS.join(", ")})`);
  const toChar: string[] = new Array(256).fill(" ");
  const fromChar = new Map<string, number>();
  for (let i = 0; i < CCSID37_FROM_40.length; i += 1) {
    const ch = String.fromCodePoint(CCSID37_FROM_40[i]);
    toChar[0x40 + i] = ch;
    if (!fromChar.has(ch)) fromChar.set(ch, 0x40 + i);
  }
  return { toChar, fromChar };
}

function table(ccsid: number): Table {
  let t = tables.get(ccsid);
  if (!t) {
    t = buildTable(ccsid);
    tables.set(ccsid, t);
  }
  return t;
}

/** Character for one EBCDIC byte. Controls, nulls and attributes become a blank. */
export function ebcdicToChar(byte: number, ccsid: number = 37): string {
  if (byte < 0x40 || byte > 0xfe) return " ";
  return table(ccsid).toChar[byte];
}

export function ebcdicToString(bytes: ArrayLike<number>, ccsid: number = 37): string {
  let out = "";
  for (let i = 0; i < bytes.length; i += 1) out += ebcdicToChar(bytes[i], ccsid);
  return out;
}

/** EBCDIC byte for one character, or undefined when the CCSID cannot represent it. */
export function charToEbcdic(ch: string, ccsid: number = 37): number | undefined {
  return table(ccsid).fromChar.get(ch);
}

/** Encode text, throwing on characters the CCSID cannot represent. */
export function stringToEbcdic(text: string, ccsid: number = 37): Uint8Array {
  const chars = Array.from(text);
  const out = new Uint8Array(chars.length);
  chars.forEach((ch, i) => {
    const byte = charToEbcdic(ch, ccsid);
    if (byte === undefined) {
      throw new Error(`Character ${JSON.stringify(ch)} cannot be represented in CCSID ${ccsid}`);
    }
    out[i] = byte;
  });
  return out;
}
